#!/bin/sh
# gen-theme.sh — generate Disjoint's dark-first theme override for Bulma v1.
#
# Bulma's precompiled CSS is light-first: the base :root carries the light
# theme, and @media (prefers-color-scheme: dark) holds only the ~48 dark
# theme variables. Disjoint is dark-first, so this script emits:
#   1. the dark-theme variables in a plain :root  (the new default), and
#   2. the full light-theme variables inside @media (prefers-color-scheme: light)
#      so light-preferring users get the light theme.
#
# The output is concatenated with web/css/site.css into web/static/disjoint.css
# by `make css`. Both the extracted blocks and the vendored bulma.min.css must
# come from the same Bulma version.
#
# Usage: gen-theme.sh /path/to/bulma/css/bulma.css   (unminified)
set -eu

CSS=${1:?usage: gen-theme.sh /path/to/bulma/css/bulma.css}

extract() {
  # Print the :root variable declarations inside @media (prefers-color-scheme: $1),
  # dedented by 2 spaces.
  awk -v scheme="$1" '
    $0 == "@media (prefers-color-scheme: " scheme ") {" { inmedia = 1; next }
    inmedia && $0 == "  :root {" { inroot = 1; next }
    inroot && $0 == "  }" { exit }
    inroot { sub(/^    /, "  "); print }
  ' "$CSS"
}

{
  cat <<'EOF'
/* Generated by web/css/gen-theme.sh — do not edit by hand.
   Regenerate with: make css  (BULMA_DIR=/path/to/bulma to point elsewhere).

   Dark-first theme for Bulma v1: the dark-theme variables below are Bulma's
   @media (prefers-color-scheme: dark) block applied as the default, and the
   light-theme variables are re-applied only when the system prefers light.
   Must stay in sync with web/static/bulma.min.css (same version). */
EOF
  printf ':root {\n'
  extract dark
  printf '}\n\n@media (prefers-color-scheme: light) {\n  :root {\n'
  extract light | sed 's/^  /    /'
  printf '  }\n}\n'
}
